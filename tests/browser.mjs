import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const base=process.env.STUDIO_URL||'http://localhost:4173';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1100}});
const errors=[];page.on('pageerror',e=>errors.push(String(e)));
await page.goto(`${base}/lab`);
await page.waitForSelector('#plane canvas');
await page.locator('.manual summary').click();
await page.locator('#manual-x').fill('0.5');
await page.locator('[data-sensor="gyro"]').click();
await page.waitForFunction(()=>document.querySelector('#trace-title')?.textContent==='Gyroscope');
await mkdir('reports',{recursive:true});
await page.screenshot({path:'reports/desktop.png',fullPage:true});
const {token}=await fetch(`${base}/api/session`).then(r=>r.json());
const phone=await browser.newPage({viewport:{width:393,height:852},isMobile:true,hasTouch:true});
phone.on('pageerror',e=>errors.push(String(e)));
await phone.goto(`${base}/phone/lab?session=${token}`);
await phone.waitForSelector('#start');
await phone.screenshot({path:'reports/phone.png',fullPage:true});
assert.deepEqual(errors,[]);
await browser.close();
console.log('Desktop rendering, manual input, signal selection, and phone layout passed. No simulated sensor data used.');
